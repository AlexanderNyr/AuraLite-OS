#!/usr/bin/env python3
"""Generate the two bitmap faces the office suite ships, as BDF.

Why BDF, and why generated
--------------------------
The kernel's PSF2 font is one 8x16 CP437 face: no Cyrillic, no proportional
metrics, no styles.  The office suite needs a body face that can set a Russian
paragraph and a UI face that can set a menu.  Both are bitmap faces at these
sizes -- hinting a scalable font at 11 px is a project of its own, and OF1's
job is text, not typography.

The bitmaps are rasterised here, once, from DejaVu (Bitstream Vera licence:
permissive, redistribution of derived bitmaps allowed; the faces are renamed
because the names are reserved).  The output is BDF 2.1 -- plain text, so a
reviewer can read a glyph, diff a change, or hand-edit a stem, and so the
loader in libaoglyph parses the same format other bitmap fonts use instead of
a private container.

Two faces:
  ao_sans_11.bdf   proportional, ascent 9, descent 3 -- body text and UI
  ao_mono_16.bdf   monospace 8x16, ascent 12, descent 4 -- code, grids, rulers

Both cover: ASCII, the Cyrillic block (U+0410-U+044F, Ё ё), Ґ ґ, and the
typographic set a Russian document actually needs: « » — – … № § ° µ.

Usage: python3 tools/gen_office_fonts.py [--check]
       --check exits non-zero when the committed .bdf no longer matches what
       this script produces, so the fonts cannot silently drift from their
       generator (the same contract tools/gen_wv_cp1251_font.py has).
"""
from __future__ import annotations

import os
import sys

from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUTDIR = os.path.join(ROOT, "userspace", "office", "fonts")

DEJAVU = "/usr/share/fonts/truetype/dejavu"
SANS = os.path.join(DEJAVU, "DejaVuSans.ttf")
MONO = os.path.join(DEJAVU, "DejaVuSansMono.ttf")

# The typographic set: every codepoint here is one the office document model
# promises to set.  Anything else the user types falls back to '?'.
#   U+00A0 nbsp  U+00A7 §  U+00B0 °  U+00B5 µ  U+00AB «  U+00BB »
#   U+2013 –  U+2014 —  U+2026 …  U+2116 №  U+0401 Ё  U+0451 ё  U+0490 Ґ
#   U+0491 ґ
EXTRA = [0x00A0, 0x00A7, 0x00B0, 0x00B5, 0x00AB, 0x00BB,
         0x2013, 0x2014, 0x2026, 0x2116, 0x0401, 0x0451, 0x0490, 0x0491]


def charset() -> list[int]:
    cps = list(range(0x20, 0x7F))          # printable ASCII
    cps += list(range(0x0410, 0x0450))     # А-я
    cps += EXTRA
    return sorted(set(cps))


def raster(font: ImageFont.FreeTypeFont, cp: int, cell_w: int, cell_h: int,
           proportional: bool):
    """Rasterise one codepoint, baseline-anchored.

    Returns (w, h, xoff, yoff, rows) in BDF's own convention: `yoff` counts
    rows from the baseline up to the bottom edge of the box, so a descender
    gives a negative yoff and a letter sitting on the baseline gives 0.  The
    anchor "ls" (left, baseline) is what makes that conversion a subtraction
    instead of a guess -- measuring from the top of the line box, as the first
    version of this script did, put '!' two rows below the baseline.
    """
    ch = chr(cp)
    try:
        l, t, r, b = font.getbbox(ch, anchor="ls")
    except Exception:
        l = t = r = b = 0
    if r <= l or b <= t:
        return (0, 0, 0, 0, [])            # blank (space, nbsp)
    w, h = r - l, b - t
    if w > cell_w:
        w = cell_w
    if h > cell_h:
        h = cell_h
    img = Image.new("L", (w, h), 0)
    ImageDraw.Draw(img).text((-l, -t), ch, fill=255, font=font, anchor="ls")
    px = img.load()
    rows = []
    for y in range(h):
        bits = 0
        for x in range(w):
            if px[x, y] >= 128:            # 1-bpp: no grey, no blending
                bits |= 1 << (w - 1 - x)
        rows.append(bits)
    return (w, h, l, -b, rows)


def build_bdf(name: str, ttf: str, px: int, cell_w: int, cell_h: int,
              ascent: int, descent: int, proportional: bool) -> str:
    font = ImageFont.truetype(ttf, px)
    cps = charset()
    glyphs = []
    for cp in cps:
        w, h, xoff, yoff, rows = raster(font, cp, cell_w, cell_h,
                                        proportional)
        if cp == 0x20:                     # space: advance only
            w = h = 0
            rows = []
        if proportional:
            adv = font.getlength(chr(cp))
            adv = max(1, int(round(adv)))
        else:
            adv = cell_w
        glyphs.append((cp, w, h, xoff, yoff, adv, rows))

    out = []
    out.append("STARTFONT 2.1")
    out.append(f"COMMENT {name} - generated by tools/gen_office_fonts.py from "
               f"{os.path.basename(ttf)} {px}px; do not hand-edit, edit the generator")
    out.append(f"FONT -auralite-{name}-Medium-R-Normal--{cell_h}-"
               f"{cell_h * 10}-75-75-{'P' if proportional else 'M'}-{cell_w * 10}-"
               "ISO10646-1")
    out.append(f"SIZE {px} 75 75")
    out.append(f"FONTBOUNDINGBOX {cell_w} {cell_h} 0 -{descent}")
    out.append("STARTPROPERTIES 6")
    out.append(f"FONT_ASCENT {ascent}")
    out.append(f"FONT_DESCENT {descent}")
    out.append(f"DEFAULT_CHAR {ord('?')}")
    out.append("PIXEL_SIZE %d" % px)
    out.append(f"SPACING \"{'P' if proportional else 'M'}\"")
    out.append("CHARSET_REGISTRY \"ISO10646\"")
    out.append("ENDPROPERTIES")
    out.append(f"CHARS {len(glyphs)}")
    for cp, w, h, xoff, yoff, adv, rows in glyphs:
        out.append(f"STARTCHAR U+{cp:04X}")
        out.append(f"ENCODING {cp}")
        out.append(f"SWIDTH {adv * 1000 // max(1, px)} {0}")
        out.append(f"DWIDTH {adv} 0")
        out.append(f"BBX {w} {h} {xoff} {yoff}")
        out.append("BITMAP")
        # BDF pads a row on the RIGHT to a whole byte, i.e. pixel 0 is the
        # MOST significant bit of the first byte.  The first version of this
        # script wrote the bits left-aligned to the glyph box instead (pixel 0
        # at bit w-1), which is identical for w == 8 and wrong for every
        # narrower glyph: the comma, the period and every narrow letter came
        # out blank in the renderer while all eight-wide letters looked perfect.
        stride = (w + 7) // 8
        hexper = stride * 2
        for bits in rows:
            if w:
                out.append(f"{bits << (stride * 8 - w):0{hexper}X}")
        out.append("ENDCHAR")
    out.append("ENDFONT")
    return "\n".join(out) + "\n"


FACES = {
    # name              ttf    px  cell   ascent descent prop
    "ao_sans_11.bdf": dict(ttf=SANS, px=13, cell_w=16, cell_h=14,
                           ascent=11, descent=3, proportional=True),
    "ao_mono_16.bdf": dict(ttf=MONO, px=15, cell_w=8, cell_h=16,
                           ascent=12, descent=4, proportional=False),
}


def main(argv: list[str]) -> int:
    check = "--check" in argv
    os.makedirs(OUTDIR, exist_ok=True)
    drift = []
    for name, kw in FACES.items():
        text = build_bdf(name[:-4], **kw)
        path = os.path.join(OUTDIR, name)
        if check:
            have = open(path, encoding="utf-8").read() if os.path.exists(path) else ""
            if have != text:
                drift.append(name)
            continue
        with open(path, "w", encoding="utf-8") as f:
            f.write(text)
        print(f"[fonts] {name}: {len(text.splitlines())} lines, "
              f"{os.path.getsize(path)} bytes")
    if check:
        if drift:
            print("[fonts] FAIL: committed font(s) differ from the generator: "
                  + ", ".join(drift))
            return 1
        print("[fonts] OK: both committed BDF faces match the generator")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
