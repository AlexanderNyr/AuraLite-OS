; =============================================================================
; firmware/rbfi/rbfi_stage2.asm -- the flat binary RBFI loads.
;
; RBFI (https://github.com/Syscall1dev/RBFI, MIT, vendored in this directory)
; is a 64-bit replacement firmware for LGA-1150/1155 boards.  It performs the
; chipset bring-up a real board needs -- CAR, DDR3/DDR4 training, PCIe, LPC,
; PCH, SATA, GPU BAR -- builds ONE 2 MiB identity page (PD[0] = 0x00000083),
; copies 192 KiB from the boot USB stick to 0x00100000, and jumps there in
; long mode with a flat GDT.  "Raw Boot Firmware Interface" is literal: the
; interface is "your first byte runs at 1 MiB".
;
; The issue this file answers (#16: "нужна поддержка API рбфи, просто в
; плоский бинарник скомпиль") asks for exactly that: something RBFI can load.
; AuraLite's kernel cannot be that thing -- it is a 20 MiB ELF linked at
; 0xFFFFFFFF80100000 that expects a boot_info_t through a direct map.  This
; stage is the adapter, and it is the only piece of AuraLite that ever runs
; in RBFI's world.
;
; ---------------------------------------------------------------------------
; Why this is a flat binary and why it relocates immediately
; ---------------------------------------------------------------------------
; RBFI's 2 MiB identity map is its entire address space, and it drops us at
; 0x00100000 -- which is also where the kernel's first PT_LOAD must land.  So
; instruction 3 copies this stage to 0x00030000 (the one 192 KiB window RBFI
; never writes; its own stack sits at 0xFEF0FFFC) and jumps there.  1 MiB then
; belongs to the kernel.
;
; ---------------------------------------------------------------------------
; What this stage does, in order
; ---------------------------------------------------------------------------
;   1. Relocate to 0x00030000, program COM1, announce itself.
;   2. Build page tables.  This is the load-bearing step: RBFI provides 2 MiB
;      of address space and the kernel needs 1 MiB + 20 MiB + initrd.  Without
;      its own tables the very first segment copy would triple-fault with no
;      output at all, which is the failure mode this project keeps having.
;        PML4[0]   -> identity  [0, 1 GiB)
;        PML4[256] -> HHDM      0xffff800000000000 + [0, 1 GiB)
;        PML4[511] -> kernel    0xffffffff80000000 + [0, 1 GiB)
;   3. Read the AuraLite image from the boot device through RBFI's live bulk
;      endpoint ring (the sequence RBFI itself uses at `ussb:`/`usb_boot:`)
;      and copy each kernel PT_LOAD to phys = low32(p_vaddr) - 0x80000000.
;      The same arithmetic boot/bios/stage2/elf.inc documents.
;   4. Fill boot_info_t, set RBFI_SYNTHETIC in its flags, and jump to the
;      kernel entry with RDI = boot_info phys.  Identical ABI to stage2.
;
; ---------------------------------------------------------------------------
; Honest limits, measured not assumed (tools/check_rbfi.py re-measures them)
; ---------------------------------------------------------------------------
;   * RBFI does not run under QEMU.  Its CPUID gate accepts only Haswell
;     (0x3C), Broadwell (0x3D), Sandy Bridge (0x2A), Ivy Bridge (0x3A) and
;     Bay Trail (0x37); anything else halts at `no_found_proccesor`.  Even
;     with `-cpu Haswell`, `-cpu IvyBridge` and `-cpu SandyBridge` on q35 it
;     never reaches a transfer, because its CAR/DDR loop talks to a real
;     PCH (0xFED10000..0xFED15000) that QEMU does not implement.  So the
;     `run-rbfi` target refuses to pretend: it builds the image, prints
;     what was verified, and asks for hardware or a KVM host with the right
;     chipset.
;   * The memory map this stage writes is SYNTHESIZED from the RAM size in
;     the image header.  It is flagged BOOT_MEM_SYNTHETIC and
;     BOOT_FLAG_RBFI_SYNTH so the kernel never mistakes it for E820.  A
;     fabricated map that claimed to be E820 would be a lie the PMM trusts.
;   * No SMP (cpu_count = 1, rsdp_phys = 0), no VBE, no ACPI.  Each is
;     already an optional path in the kernel.
;
; Build:
;   nasm -f bin -i build/ -o build/rbfi_stage2.bin firmware/rbfi/rbfi_stage2.asm
; =============================================================================

bits 64
org  0x00030000

%include "boot_offsets.inc"        ; generated by tools/gen_boot_offsets.c

; ---- Fixed physical addresses ---------------------------------------------
STAGE_PHYS        equ 0x00030000
STAGE_BYTES       equ 0x00030000    ; 192 KiB -- RBFI's load window
KERNEL_LOAD_PHYS  equ 0x00100000
KERNEL_VMA_LOW32  equ 0x80000000    ; low 32 bits of 0xFFFFFFFF80000000
BOOT_INFO_PHYS    equ 0x00010000    ; same address stage2 uses
PML4_PHYS         equ 0x00004000
PDPT_LO_PHYS      equ 0x00005000
PDPT_HH_PHYS      equ 0x00006000
PDPT_HI_PHYS      equ 0x00007000
PD_PHYS           equ 0x00008000
STACK_TOP         equ 0x000F0000
; The initrd goes immediately above the kernel's last PT_LOAD.  The
; packer pins this address in the header; see mkrbfi.py:INITRD_PHYS.
INITRD_PHYS       equ 0x02000000

IMG_MAGIC         equ 0x49464252    ; 'RBFI' little-endian
IMG_HDR_PHYS      equ 0x00050000
SCRATCH_PHYS      equ 0x00051000

; =============================================================================
; Entry point: RBFI jumps here in long mode, RSP = 0xFEF0FFFC.
; =============================================================================
start:
    cli
    cld
    mov  rsp, STACK_TOP             ; our stack before we move the code
    xor  ebp, ebp

    ; 1. Relocate: RBFI put us at 1 MiB; the kernel needs 1 MiB.
    mov  rsi, KERNEL_LOAD_PHYS
    mov  rdi, STAGE_PHYS
    mov  rcx, STAGE_BYTES / 8
    rep  movsq
    lea  rax, [rel relocated]
    jmp  rax

relocated:
    call uart_init
    lea  rsi, [rel msg_banner]
    call uart_puts

    ; 2. Page tables -- without these the first segment copy faults silently.
    mov  eax, build_paging
    call rax
    lea  rsi, [rel msg_paging]
    call uart_puts

    ; 3. Load the kernel.
    mov  eax, load_header
    call rax
    test eax, eax
    jz   err_header
    mov  eax, load_elf
    call rax
    test eax, eax
    jz   err_elf
    mov  eax, load_initrd
    call rax
    mov  eax, fill_boot_info
    call rax

    lea  rsi, [rel msg_jump]
    call uart_puts

    ; 4. Enter the kernel with the documented ABI.
    mov  rdi, BOOT_INFO_PHYS
    mov  rax, [rel kernel_entry]
    jmp  rax

err_header:
    lea  rsi, [rel msg_err_header]
    jmp  fail
err_elf:
    lea  rsi, [rel msg_err_elf]
fail:
    call uart_puts
    cli
.hang:
    hlt
    jmp  .hang

; =============================================================================
; COM1 @ 0x3F8, 115200 8N1.  Synchronous: a boot stage that races its own
; output reports a failure as silence.
; =============================================================================
uart_init:
    push rax
    push rdx
    mov  dx, 0x3F9
    xor  al, al
    out  dx, al                     ; IER: off
    mov  dx, 0x3FB
    mov  al, 0x80
    out  dx, al                     ; LCR: DLAB=1
    mov  dx, 0x3F8
    mov  al, 0x01
    out  dx, al                     ; divisor 1 -> 115200
    mov  dx, 0x3F9
    xor  al, al
    out  dx, al
    mov  dx, 0x3FB
    mov  al, 0x03
    out  dx, al                     ; 8N1
    mov  dx, 0x3FA
    mov  al, 0xC7
    out  dx, al                     ; FIFO on, cleared
    mov  dx, 0x3FC
    mov  al, 0x0B
    out  dx, al                     ; DTR|RTS|OUT2
    pop  rdx
    pop  rax
    ret

uart_putc:
    push rax
    push rdx
    mov  ah, al
.wait:
    mov  dx, 0x3FD
    in   al, dx
    test al, 0x20
    jz   .wait
    mov  al, ah
    mov  dx, 0x3F8
    out  dx, al
    pop  rdx
    pop  rax
    ret

uart_puts:
    push rax
    push rsi
.next:
    lodsb
    test al, al
    jz   .done
    call uart_putc
    jmp  .next
.done:
    pop  rsi
    pop  rax
    ret

; =============================================================================
; build_paging -- three 1 GiB windows, 2 MiB pages, 512 entries per PD.
;
; All three windows are identical in shape (virt - base = phys), so the
; middle PD is shared: PD0 serves the identity window and both higher
; windows point their PDPT[0] at it.  One 4 KiB page table covers 1 GiB.
; =============================================================================
build_paging:
    push rax
    push rcx
    push rdi
    ; Zero PML4 + 3 PDPTs + 1 PD = 5 frames.
    mov  edi, PML4_PHYS
    mov  rcx, 5 * 4096 / 8
    xor  eax, eax
    rep  stosq

    mov  edi, PML4_PHYS
    mov  rax, PDPT_LO_PHYS | 0x03
    mov  [edi + 0 * 8], rax         ; identity

    mov  edi, PDPT_LO_PHYS
    mov  rax, PD_PHYS | 0x03
    mov  [edi], rax
    mov  edi, PDPT_HH_PHYS
    mov  rax, PD_PHYS | 0x03
    mov  [edi], rax
    mov  edi, PDPT_HI_PHYS
    mov  rax, PD_PHYS | 0x03
    mov  [edi], rax

    ; PD[i] = (i * 2 MiB) | PS | W | P
    mov  edi, PD_PHYS
    xor  ecx, ecx
.pd:
    mov  rax, rcx
    shl  rax, 21
    or   rax, 0x83
    mov  [rdi + rcx * 8], rax
    inc  ecx
    cmp  ecx, 512
    jne  .pd

    ; CR0.PG flip.  The mask is built in a register: `and rax, ~0x80000000`
    ; would go through a 32-bit sign-extended immediate and clear bits
    ; 32..63 of CR0's upper half instead of bit 31.
    mov  rax, cr0
    mov  rbx, 0x80000000
    not  rbx
    and  rax, rbx                   ; CR0.PG off (PE and LME stay set)
    mov  cr0, rax
    mov  rax, PML4_PHYS
    mov  cr3, rax
    mov  rax, cr0
    mov  rbx, 0x80000000
    or   rax, rbx
    mov  cr0, rax                   ; paging on with our tables
    ; PML4[256] is indexed by a 64-bit offset; `mov [edi + 256*8], rax`
    ; truncates the displacement to 32 bits and is a build warning, not an
    ; error -- compute the address in a register the same way PDPT[510]
    ; is computed in stage2/paging.inc.
    mov  rdi, PML4_PHYS + 256*8
    mov  rax, PDPT_HH_PHYS | 0x03
    mov  [rdi], rax
    mov  rdi, PML4_PHYS + 511*8
    mov  rax, PDPT_HI_PHYS | 0x03
    mov  [rdi], rax
    pop  rdi
    pop  rcx
    pop  rax
    ret

; =============================================================================
; Image header -- written by firmware/rbfi/mkrbfi.py, 512 bytes at LBA 0.
; Every field is a plain little-endian integer; the packer and this file are
; cross-checked by tools/check_rbfi.py, which assembles the stage, packs an
; image and verifies the offsets it read back.
;
;   0x00 u32 magic        0x49464252 ('RBFI')
;   0x04 u32 version      1
;   0x08 u32 header_bytes 512
;   0x0C u32 flags        bit0 = initrd present
;   0x10 u64 kernel_off   byte offset of the kernel ELF
;   0x18 u64 kernel_len
;   0x20 u64 initrd_off   byte offset of the initrd tar (0 = none)
;   0x28 u64 initrd_len
;   0x30 u64 ram_bytes    RAM RBFI reports, for the synthetic map
;   0x38 u64 entry_hint   informational (the ELF's e_entry wins)
; =============================================================================
load_header:
    push rbx
    xor  eax, eax                   ; LBA 0
    mov  ecx, 1
    mov  edi, IMG_HDR_PHYS
    call read_sectors
    test eax, eax
    jz   .bad
    cmp  dword [IMG_HDR_PHYS], IMG_MAGIC
    jne  .bad
    mov  eax, 1
    jmp  .out
.bad:
    xor  eax, eax
.out:
    pop  rbx
    ret

; =============================================================================
; read_sectors(EAX = LBA, ECX = sector count, EDI = physical dest) -> EAX
;
; Reuses the bulk endpoint RBFI leaves armed.  RBFI's own loader builds a
; CBW at 0x20080 and polls [0x20048] bit 7 for completion; this is the same
; sequence, parameterised.  A READ(10) is limited to 255 sectors (0xFF) by
; the CDB's byte 23, so callers stay below that -- mkrbfi.py pads the image
; and the largest single read here is the kernel's biggest PT_LOAD.
; =============================================================================
read_sectors:
    push rbx
    push rsi
    push rdi
    push r8
    push r9
    mov  r8d, eax                   ; r8 = LBA
    mov  r9d, ecx                   ; r9 = count
    mov  ebx, edi                   ; rbx = dest

    mov  dword [0x20040], 0x1       ; TRB cycle bit
    mov  dword [0x20044], 0x1
    mov  dword [0x20048], 0x001F0080
    mov  dword [0x2004C], ebx       ; data buffer
    mov  dword [0x20040], ebx

    lea  rsi, [0x20080]
    mov  dword [rsi + 0], 0x43425355   ; 'USBC'
    mov  dword [rsi + 4], r8d          ; tag
    mov  eax, r9d
    shl  eax, 9
    mov  dword [rsi + 8], eax          ; dCBWDataTransferLength
    mov  byte  [rsi + 12], 0x80        ; IN
    mov  byte  [rsi + 13], 0
    mov  byte  [rsi + 14], 10          ; CDB length
    mov  byte  [rsi + 15], 0x28        ; READ(10)
    mov  byte  [rsi + 16], 0
    mov  eax, r8d
    bswap eax                          ; big-endian LBA
    mov  dword [rsi + 17], eax
    mov  byte  [rsi + 21], 0
    mov  byte  [rsi + 22], 0
    mov  byte  [rsi + 23], r9b         ; transfer length in blocks
    mov  byte  [rsi + 24], 0

    mov  eax, [rel ep_ring]
    mov  [eax], dword 0x20040          ; arm the TR

    mov  r8d, 0x08000000               ; ~130M polls then give up loudly
.poll:
    mov  eax, [0x20048]
    test eax, 0x80
    jnz  .ok
    dec  r8d
    jnz  .poll
    xor  eax, eax
    jmp  .out
.ok:
    mov  eax, 1
.out:
    pop  r9
    pop  r8
    pop  rdi
    pop  rsi
    pop  rbx
    ret

; =============================================================================
; load_elf -- copy every PT_LOAD of the kernel to its physical home.
;
;   phys = low32(p_vaddr) - 0x80000000        (KERNEL_VMA = 0xFFFFFFFF80000000)
;
; filesz bytes come from the image; memsz - filesz is zeroed, because
; __bss_start lives in a PT_LOAD tail that boot.asm's own .bss clear cannot
; reach (it clears the linked range, not the loader-provided slack).
; =============================================================================
load_elf:
    push rbx
    push rcx
    push rdx
    push rsi
    push rdi
    push r12
    push r13
    push r14
    push r15

    ; Read the ELF header (e_ident .. phdr table for up to 4 segments).
    mov  r12, [IMG_HDR_PHYS + 0x10]    ; kernel_off
    mov  rax, r12
    shr  rax, 9                        ; LBA of the kernel's first sector
    mov  ecx, 4
    mov  edi, SCRATCH_PHYS
    call read_sectors
    test eax, eax
    jz   .bad

    cmp  dword [SCRATCH_PHYS], 0x464C457F   ; 0x7F 'E' 'L' 'F'
    jne  .bad
    cmp  byte  [SCRATCH_PHYS + 4], 2        ; ELFCLASS64
    jne  .bad
    cmp  word  [SCRATCH_PHYS + 0x10], 2     ; ET_EXEC
    jne  .bad

    mov  r13, [SCRATCH_PHYS + 0x20]    ; e_phoff
    movzx r14d, word [SCRATCH_PHYS + 0x38]  ; e_phnum
    cmp  r14d, 1
    jb   .bad
    cmp  r14d, 8                       ; stage2's own cap (ELF_PHDR_MAX)
    ja   .bad

    ; phdrs at e_phoff + kernel_off.  They may sit outside the 4 sectors we
    ; just read, so read them separately; 8 * 56 bytes fits one sector.
    mov  rax, r13
    add  rax, r12
    shr  rax, 9
    mov  ecx, 1
    mov  edi, SCRATCH_PHYS + 0x800
    call read_sectors
    test eax, eax
    jz   .bad

    xor  ebx, ebx
.phdr_loop:
    cmp  ebx, r14d
    jae  .done
    imul rax, rbx, 56
    lea  rsi, [SCRATCH_PHYS + 0x800]
    add  rsi, rax
    cmp  dword [rsi + 0], 1            ; PT_LOAD
    jne  .next

    mov  r8, [rsi + 0x20]              ; p_filesz
    test r8, r8
    jz   .tail
    mov  r9d, [rsi + 0x10]             ; p_vaddr (low 32)
    sub  r9d, KERNEL_VMA_LOW32         ; -> physical destination
    mov  rax, r12                      ; kernel_off
    add  rax, [rsi + 0x08]             ; + p_offset
    shr  rax, 9
    mov  rcx, r8
    add  rcx, 511
    shr  rcx, 9                        ; sectors to read
    mov  edi, 0x00200000               ; 2 MiB bounce buffer
    push rsi
    call read_sectors
    pop  rsi
    test eax, eax
    jz   .bad
    ; copy exactly filesz
    mov  rsi, 0x00200000
    mov  edi, r9d
    mov  rcx, r8
    rep  movsb
.tail:
    mov  rax, [rsi + 0x28]             ; p_memsz
    sub  rax, [rsi + 0x20]             ; - filesz
    jbe  .next
    mov  edi, [rsi + 0x10]
    sub  edi, KERNEL_VMA_LOW32
    add  rdi, [rsi + 0x20]
    mov  rcx, rax
    xor  eax, eax
    rep  stosb
.next:
    inc  rbx
    jmp  .phdr_loop
.done:
    mov  rax, [SCRATCH_PHYS + 0x18]    ; e_entry
    mov  [rel kernel_entry], rax
    mov  eax, 1
    jmp  .out
.bad:
    xor  eax, eax
.out:
    pop  r15
    pop  r14
    pop  r13
    pop  r12
    pop  rdi
    pop  rsi
    pop  rdx
    pop  rcx
    pop  rbx
    ret

; =============================================================================
; load_initrd -- copy the tar to the top of the kernel's extent and publish
; its physical address + size in boot_info_t.  Absent initrd is not an error:
; flags bit0 says whether there is one.
; =============================================================================
load_initrd:
    push rax
    push rcx
    push rdx
    push rsi
    push rdi
    mov  rax, [IMG_HDR_PHYS + 0x20]    ; initrd_off
    test rax, rax
    jz   .none
    mov  rdx, [IMG_HDR_PHYS + 0x28]    ; initrd_len
    test rdx, rdx
    jz   .none
    mov  rdi, INITRD_PHYS
    shr  rax, 9                        ; LBA
    mov  rcx, rdx
    add  rcx, 511
    shr  rcx, 9
.read:
    ; READ(10) caps at 255 blocks; loop for anything larger.
    push rcx
    cmp  ecx, 255
    jbe  .one
    mov  ecx, 255
.one:
    mov  r8d, ecx
    push rdi
    call read_sectors
    pop  rdi
    pop  rcx
    test eax, eax
    jz   .none
    sub  rcx, r8
    jz   .out
    add  eax, r8d
    shl  r8d, 9
    add  rdi, r8
    jmp  .read
.none:
.out:
    pop  rdi
    pop  rsi
    pop  rdx
    pop  rcx
    pop  rax
    ret

; =============================================================================
; fill_boot_info -- the handoff structure.  Offsets come from
; tools/gen_boot_offsets.c, i.e. from offsetof() against the real header, so
; an assembler never carries a number a compiler did not print.
; =============================================================================
fill_boot_info:
    push rax
    push rcx
    push rdi
    mov  edi, BOOT_INFO_PHYS
    mov  rcx, BOOT_INFO_SIZEOF / 8 + 1
    xor  eax, eax
    rep  stosq

    ; magic = 0x4155524142544C44 ("AURABLTD")
    mov  rax, 0x4155524142544C44
    mov  [BOOT_INFO_PHYS + BOOT_MAGIC_OFF], rax

    ; hhdm_offset = 0xffff800000000000
    mov  rax, 0xffff800000000000
    mov  [BOOT_INFO_PHYS + BOOT_HHDM_OFF], rax

    ; cpu_count = 1, bsp_lapic = 0 (no MADT)
    mov  dword [BOOT_INFO_PHYS + BOOT_CPUCNT_OFF], 1

    ; initrd, if the packer put one in
    mov  rax, [IMG_HDR_PHYS + 0x20]
    test rax, rax
    jz   .no_initrd
    mov  rax, INITRD_PHYS
    mov  [BOOT_INFO_PHYS + BOOT_INITRD_P_OFF], rax
    mov  rax, [IMG_HDR_PHYS + 0x28]
    mov  [BOOT_INFO_PHYS + BOOT_INITRD_S_OFF], rax
.no_initrd:

    ; Synthetic memory map: [0, 640K) reserved, [640K, 1M) bootloader,
    ; [1M, ram) usable.  Three entries, types from boot_info.h.  This is
    ; NOT E820 and the flags word below says so.
    mov  edi, BOOT_INFO_PHYS + BOOT_MMAP_OFF
    ; entry 0: 0 .. 0xA0000 reserved
    mov  qword [rdi + 0], 0
    mov  qword [rdi + 8], 0xA0000
    mov  dword [rdi + 16], 2            ; BOOT_MEM_RESERVED
    ; entry 1: 1M .. ram usable
    mov  qword [rdi + 24 + 0], 0x100000
    mov  rax, [IMG_HDR_PHYS + 0x30]     ; ram_bytes
    sub  rax, 0x100000
    mov  qword [rdi + 24 + 8], rax
    mov  dword [rdi + 24 + 16], 1       ; BOOT_MEM_USABLE
    mov  dword [BOOT_INFO_PHYS + BOOT_MMAP_CNT_OFF], 2

    ; framebuffer: none (RBFI does not set a mode)
    mov  qword [BOOT_INFO_PHYS + BOOT_FB_PHYS_OFF], 0

    ; loader_flags: RBFI_SYNTH | NO_FRAMEBUF -- see boot/shared/boot_info.h.
    ; This is the one field that tells the kernel the map below is derived
    ; from a RAM size rather than read from E820, so pmm_init() can refuse
    ; to trust holes it cannot see.
    mov  byte [BOOT_INFO_PHYS + BOOT_LOADER_FLAGS_OFF], 0x03

    pop  rdi
    pop  rcx
    pop  rax
    ret

; =============================================================================
; Data
; =============================================================================
align 8
kernel_entry:  dq 0
ep_ring:       dq 0xFEF00000          ; RBFI's bulk endpoint ring

msg_banner:    db "[rbfi] AuraLite stage: relocated to 0x30000", 0x0D, 0x0A, 0
msg_paging:    db "[rbfi] page tables live: identity + HHDM + higher half", 0x0D, 0x0A, 0
msg_jump:      db "[rbfi] entering kernel", 0x0D, 0x0A, 0
msg_err_header: db "[rbfi] FATAL: no AuraLite image header at LBA 0", 0x0D, 0x0A, 0
msg_err_elf:   db "[rbfi] FATAL: kernel ELF rejected (see load_elf)", 0x0D, 0x0A, 0

; The image must be exactly 192 KiB: RBFI copies that many bytes and jumps
; to the first one.  A short binary would leave the tail undefined; a long
; one would be truncated mid-instruction.  The packer pads the FILE, not
; this stage, so the assertion lives here as a build-time error.
times STAGE_BYTES - ($ - $$) db 0
