/* SPDX-License-Identifier: Apache-2.0.  Written for AuraLite OS; mingw-w64's
 * public headers are used as a declaration source only, and every symbol below
 * goes through the personality's own LoadLibraryA/GetProcAddress by NAME.
 *
 * w32/tests/w32c8_static_slice.c -- RESIDUE3_PLAN.md phase C8, box 2 (RES-57).
 *
 * The five app ledgers carry 1694 `static-only` markers: symbols the apps
 * import, that the personality's export tables provide, and that nothing has
 * ever been watched binding from the guest side.  RES-57 says so in the ledger:
 * "bound but never called at runtime".
 *
 * This fixture closes the *binding* half by measurement, and demonstrates the
 * calling half on a slice:
 *
 *   1. LoadLibraryA for each of the 20 DLLs the markers name;
 *   2. GetProcAddress for each of the 820 distinct named pairs, per DLL,
 *      printing `[w32] STATIC-ONLY <dll>: <have>/<total> resolved`;
 *   3. every pair that comes back NULL is printed by name -- an import marker
 *      over a symbol the personality does not actually export is a ledger
 *      error and this is where it would show;
 *   4. a 30-call slice of argument-free stubs (three to eight per DLL) is
 *      *called*, not just resolved, so the FAIL-CLEAN notes fire and the
 *      receipts are the personality's own;
 *   5. exit 78 on a clean run, 1 if any resolution or call disagrees with the
 *      table the host generated.
 *
 * The name/count tables are generated by tools/w32_static_slice.py from the
 * ledgers and the export tables, so the guest and the host cannot disagree
 * about what the list is.
 */

/* GetProcAddress returns FARPROC; the casts below are the point of the test,
 * so the diagnostic that they are incompatible types is silenced where it
 * applies rather than globally. */
#pragma GCC diagnostic ignored "-Wcast-function-type"

#include <windows.h>

#define K_SO_PAIR_FIRST /* marker: the table below needs w32_so_pair_t */

typedef struct { const char *dll; const char *sym; } w32_so_pair_t;

#include "w32_static_slice.h"

static HANDLE out;
static unsigned bad_count;

static unsigned long slen(const char *s) {
    const char *p = s;
    while (*p) p++;
    return (unsigned long)(p - s);
}

static void say(const char *s) {
    DWORD n = 0;
    WriteFile(out, s, (DWORD)slen(s), &n, NULL);
}

static void say_dec(unsigned long v) {
    char buf[24];
    int i = 23;
    buf[i--] = 0;
    if (!v) buf[i--] = '0';
    while (v) { buf[i--] = (char)('0' + (v % 10)); v /= 10; }
    say(&buf[i + 1]);
}

static void say_key(const char *dll, const char *sym) {
    say("[w32] STATIC-ONLY MISSING ");
    say(dll);
    say("!");
    say(sym);
    say("\r\n");
}

int winstart(void) {
    out = GetStdHandle((DWORD)-11);
    if (out == INVALID_HANDLE_VALUE) out = GetStdHandle((DWORD)-12);

    say("C8: static-only receipts (RES-57: 1694 markers, ");
    say_dec((unsigned long)K_SO_TOTAL);
    say(" distinct named pairs)\r\n");

    /* 1. LoadLibraryA for every DLL the markers name. */
    HMODULE mod[K_SO_DLLS];
    unsigned dlls_ok = 0;
    for (unsigned i = 0; i < (unsigned)K_SO_DLLS; i++) {
        mod[i] = LoadLibraryA(k_so_dlls[i]);
        if (mod[i]) dlls_ok++;
        else {
            say("[w32] STATIC-ONLY MISSING MODULE ");
            say(k_so_dlls[i]);
            say("\r\n");
            bad_count++;
        }
    }
    say("[w32] STATIC-ONLY modules: ");
    say_dec(dlls_ok);
    say("/");
    say_dec((unsigned long)K_SO_DLLS);
    say(" loaded\r\n");

    /* 2/3. Resolve every pair; count per DLL and name every NULL. */
    unsigned resolved = 0;
    for (unsigned i = 0; i < (unsigned)K_SO_DLLS; i++) {
        if (!mod[i]) continue;
        unsigned have = 0, total = 0;
        for (unsigned p = 0; p < (unsigned)K_SO_PRINTED; p++) {
            if (lstrcmpiA(k_so_printed[p].dll, k_so_dlls[i]) != 0) continue;
            total++;
            void *fp = (void *)GetProcAddress(mod[i], k_so_printed[p].sym);
            if (fp) have++;
            else {
                say_key(k_so_printed[p].dll, k_so_printed[p].sym);
                bad_count++;
            }
        }
        if (!total) continue;
        resolved += have;
        say("[w32] STATIC-ONLY ");
        say(k_so_dlls[i]);
        say(": ");
        say_dec(have);
        say("/");
        say_dec(total);
        say(" resolved via GetProcAddress\r\n");
        if (have != total) bad_count++;
    }

    /* K_SO_MISSING is 0 today; the loop stays so a future ledger/tables
     * disagreement prints names instead of only a count. */
    for (int p = 0; p < (int)K_SO_MISSING; p++)
        say_key(k_so_missing[p].dll, k_so_missing[p].sym);

    say("[w32] STATIC-ONLY ");
    say_dec(resolved);
    say("/");
    say_dec((unsigned long)K_SO_PRINTED);
    say(" resolved over ");
    say_dec((unsigned long)K_SO_DLLS);
    say(" modules (");
    say_dec((unsigned long)K_SO_ORDINALS);
    say(" further markers are ordinal imports: no name to resolve)\r\n");
    if (resolved != (unsigned)K_SO_PRINTED) bad_count++;

    /* 4. Call the slice.  These are the generated FAIL-CLEAN stubs, which take
     * no arguments, so calling them through a `(void)` pointer cannot walk off
     * the stack -- and the answer each one produces is its own receipt. */
    unsigned called = 0, calls_real = 0;
    for (unsigned c = 0; c < (unsigned)K_SO_CALLS; c++) {
        unsigned idx = 0;
        int found = 0;
        for (unsigned i = 0; i < (unsigned)K_SO_DLLS && !found; i++) {
            if (lstrcmpiA(k_so_callable[c].dll, k_so_dlls[i]) != 0) continue;
            idx = i;
            found = 1;
        }
        if (!found || !mod[idx]) { bad_count++; continue; }
        void *fp = (void *)GetProcAddress(mod[idx], k_so_callable[c].sym);
        if (!fp) { bad_count++; continue; }
        unsigned long long (*fn)(void) = (unsigned long long (*)(void))fp;
        unsigned long long r = fn();
        say("[w32] STATIC-ONLY call ");
        say(k_so_callable[c].dll);
        say("!");
        say(k_so_callable[c].sym);
        say(" -> 0x");
        {
            char hex[20];
            int i2 = 0;
            for (int shift = 60; shift >= 0; shift -= 4) {
                int nib = (int)((r >> shift) & 0xF);
                hex[i2++] = (char)(nib < 10 ? '0' + nib : 'a' + nib - 10);
            }
            hex[i2] = 0;
            say(hex);
        }
        say(" (called, not merely bound)\r\n");
        called++;
    }
    say("[w32] STATIC-ONLY calls: ");
    say_dec(called);
    say("/");
    say_dec((unsigned long)K_SO_CALLS);
    say(" made\r\n");
    if (called != (unsigned)K_SO_CALLS) bad_count++;

    /* 4b. A hand-written slice of the *real* implementations the markers
     * name -- the ones the argument-free rule above has to skip.  Four calls
     * with their real prototypes, so the receipt is about more than stubs:
     * static-only does not mean "stub", it means "nobody watched it". */
    {
        HMODULE u = LoadLibraryA("user32.dll");
        HMODULE k = LoadLibraryA("kernel32.dll");
        if (u) {
            int (*p_gsm)(int) = (int (*)(int))GetProcAddress(u, "GetSystemMetrics");
            if (!p_gsm) { bad_count++; }
            else {
                say("[w32] STATIC-ONLY call user32.dll!GetSystemMetrics(0) -> ");
                say_dec((unsigned long)(unsigned)p_gsm(0));
                say(" (real implementation, hand-written prototype)\r\n");
                calls_real++;
            }
        } else bad_count++;
        if (k) {
            DWORD (*p_gv)(void) = (DWORD (*)(void))GetProcAddress(k, "GetVersion");
            DWORD (*p_acp)(void) = (DWORD (*)(void))GetProcAddress(k, "GetACP");
            LCID (*p_lcid)(void) = (LCID (*)(void))GetProcAddress(k, "GetUserDefaultLCID");
            if (!p_gv || !p_acp || !p_lcid) { bad_count++; }
            else {
                say("[w32] STATIC-ONLY call kernel32.dll!GetVersion() -> 0x");
                {
                    char hex[20];
                    DWORD r2 = p_gv();
                    int i2 = 0;
                    for (int shift = 28; shift >= 0; shift -= 4) {
                        int nib = (int)((r2 >> shift) & 0xF);
                        hex[i2++] = (char)(nib < 10 ? '0' + nib : 'a' + nib - 10);
                    }
                    hex[i2] = 0;
                    say(hex);
                }
                say(" (packed major.minor.build)\r\n");
                say("[w32] STATIC-ONLY call kernel32.dll!GetACP() -> ");
                say_dec((unsigned long)p_acp());
                say("\r\n");
                say("[w32] STATIC-ONLY call kernel32.dll!GetUserDefaultLCID() -> 0x");
                say_dec((unsigned long)p_lcid());
                say("\r\n");
                calls_real += 3;
            }
        } else bad_count++;
        say("[w32] STATIC-ONLY real calls: ");
        say_dec(calls_real);
        say("/4\r\n");
    }

    if (bad_count) {
        say("[w32] STATIC-ONLY FAIL ");
        say_dec(bad_count);
        say(" disagreement(s) with the generated table\r\n");
        say("C8-STATIC-FAIL\r\n");
        ExitProcess(1);       /* a plain `return` from the entry point exits
                               * 0 through w32run, so the code is set here */
    }
    say("C8-STATIC-OK\r\n");
    ExitProcess(78);
}
